type RawMessages = typeof messages;
export type MessageKey = keyof RawMessages["zh-CN"];
export type AppMessages = Record<MessageKey, string>;

export function isSupportedLocale(locale: string): locale is AppLocale {
  return supportedLocales.includes(locale as AppLocale);
}

export function resolveLocale(locale?: string | null): AppLocale {
  if (!locale) {
    return defaultLocale;
  }

  return isSupportedLocale(locale) ? locale : defaultLocale;
}

export function getMessages(locale: AppLocale): AppMessages {
  return messages[locale];
}

export function formatMessage(
  messagesForLocale: AppMessages,
  key: MessageKey,
  values?: Record<string, string | number>,
) {
  const template: string = messagesForLocale[key] ?? key;

  if (!values) {
    return template;
  }

  return Object.entries(values).reduce<string>(
    (message, [token, value]) =>
      message.replaceAll(`{${token}}`, String(value)),
    template,
  );
}

const adminMessages: Record<AppLocale, AdminMessages> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export function createAdminTranslator(locale: AppLocale) {
  return (key: AdminMessageKey, params: Record<string, string | number> = {}) => {
    let value: string = adminMessages[locale][key];
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  };
}

export function getAdminSystemRolePresentation(
  t: ReturnType<typeof createAdminTranslator>,
  systemKey: AdminSystemRoleKey,
) {
  const keys = adminSystemRoleMessageKeys[systemKey];
  return {
    description: t(keys.description),
    name: t(keys.name),
  };
}
